def write_csv(path, rows):
    with path.open('w', encoding='utf-8-sig', newline='') as stream:
        writer = csv.writer(stream)
        writer.writerow(['id', 'english', 'turkish'])
        writer.writerows(rows)


def cmd_build(_args):
    manifest: dict = dict(seed=SEED, sources={}, overlap={}, counts={})
    rows = build_math(manifest) + build_code(manifest) + build_tools(manifest) + build_en_general(manifest) + \
        build_tr_general(manifest)
    manifest['constraint_kinds_in_tr_general'] = dict(sorted(Counter(
        i['type'] for r in rows if r['category'] == 'tr_general' for i in r['check']['items']).items()))
    for category in QUOTA:
        manifest['counts'][category] = sum(r['category'] == category for r in rows)
    ids = [r['id'] for r in rows]
    assert len(ids) == len(set(ids))
    manifest['thinking_on_share'] = round(sum(r['thinking'] for r in rows if r['split'] == 'train') /
                                          sum(r['split'] == 'train' for r in rows), 3)
    EXP.mkdir(parents=True, exist_ok=True)
    (EXP / 'worksheets').mkdir(exist_ok=True)
    (EXP / 'prompts-en.jsonl').write_text(''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in rows),
                                          encoding='utf-8', newline='\n')
    (EXP / 'wrappers.json').write_text(json.dumps(dict(templates=WRAPPERS, pool=WRAPPER_POOL), indent=1, ensure_ascii=False) + '\n',
                                       encoding='utf-8', newline='\n')
    wrap_rows = [[f'{cat}:{wid}', tpl, ''] for cat, group in WRAPPERS.items() for wid, tpl in group.items() if wid != 'bare']
    write_csv(EXP / 'worksheets/00-wrappers.csv', wrap_rows)
    for file, category, field in WORKSHEETS:
        write_csv(EXP / 'worksheets' / file, [[r['id'], r['en'][field], ''] for r in rows if r['category'] == category])
    (EXP / 'build-manifest.json').write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + '\n',
                                             encoding='utf-8', newline='\n')
    prompts_hash = sha256((EXP / 'prompts-en.jsonl').read_bytes())
    print(json.dumps(dict(counts=manifest['counts'], overlap=manifest['overlap'], prompts_sha256=prompts_hash[:16]), indent=1))


