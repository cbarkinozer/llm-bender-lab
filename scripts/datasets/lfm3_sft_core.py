def sha256(data):
    return hashlib.sha256(data).hexdigest()


def rank(key):
    return sha256(f'{SEED}:{key}'.encode())


def pick(key, pool):
    return pool[int(rank(key)[:8], 16) % len(pool)]


def thinking_for(row_id):
    return int(rank(f'think:{row_id}')[:8], 16) % 100 < 80  # owner: thinking on is the assumed mode; 20% off rows


def norm_num(token):
    token = token.replace(',', '')
    if re.fullmatch(r'\d{1,3}(\.\d{3})+', token):
        token = token.replace('.', '')
    if '.' in token:
        token = token.rstrip('0').rstrip('.')
    return token


def norm_text(text):
    return re.sub(r'\s+', ' ', re.sub(r'[^\w\s]', ' ', text.lower())).strip()


def words(text):
    return set(norm_text(text).split())


def load_rows(key):
    import pyarrow.parquet as pq
    repo, revision, file, count, _ = SOURCES[key]
    folder = CACHE / repo.replace('/', '__')
    path = folder / file
    if not path.exists():
        from huggingface_hub import HfApi, hf_hub_download
        full = HfApi().dataset_info(repo, revision=revision).sha
        hf_hub_download(repo, file, repo_type='dataset', revision=full, local_dir=str(folder))
    if file.endswith('.json'):
        rows = json.loads(path.read_text(encoding='utf-8'))
    elif file.endswith('.jsonl'):
        rows = [json.loads(s) for s in path.read_text(encoding='utf-8').split('\n') if s.strip()]
    else:
        rows = pq.read_table(path).to_pylist()
    if len(rows) != count:
        raise ValueError(f'unexpected row count for {key}: {len(rows)} != {count}')
    return rows, sha256(path.read_bytes())


def source_info(key, digest):
    repo, revision, file, count, lic = SOURCES[key]
    return dict(repo=repo, revision=revision, file=file, rows=count, license=lic, sha256=digest)


def gsm_gold(answer):
    match = re.search(r'####\s*([-\d.,]+)', answer)
    return norm_num(match.group(1)) if match else None


def gsm_bucket(answer):
    steps = answer.count('<<')
    return 1 if steps <= 2 else 2 if steps == 3 else 3 if steps == 4 else 4


def eval_math_sources():
    """Indices of GSM8K test items used by eval v2 (never trained on) and their question texts."""
    path = EVAL_V2 / 'math-pairs.jsonl'
    rows = [json.loads(s) for s in path.read_text(encoding='utf-8').split('\n') if s.strip()]
    return sorted({r['source_index'] for r in rows if r['language'] == 'en'})


# ---------------------------------------------------------------------------------------------- math

def build_math(manifest):
    train, d1 = load_rows('gsm8k-train')
    test, d2 = load_rows('gsm8k-test')
    manifest['sources']['gsm8k-train'] = source_info('gsm8k-train', d1)
    manifest['sources']['gsm8k-test'] = source_info('gsm8k-test', d2)
    eval_idx = eval_math_sources()
    assert len(eval_idx) == 152, len(eval_idx)
    eval_text = {norm_text(test[i]['question']) for i in eval_idx}

    def pick_bucketed(rows, indices, per_bucket, tag):
        buckets = {1: [], 2: [], 3: [], 4: []}
        for i in indices:
            if gsm_gold(rows[i]['answer']) is not None:
                buckets[gsm_bucket(rows[i]['answer'])].append(i)
        out = []
        for b in buckets:
            ranked = sorted(buckets[b], key=lambda i: rank(f'{tag}:{i}'))
            if len(ranked) < per_bucket:
                raise ValueError(f'{tag} bucket {b} has {len(ranked)} items')
            out.extend(ranked[:per_bucket])
        return sorted(out, key=lambda i: rank(f'order:{tag}:{i}'))

    holdout_pool = [i for i in range(len(test)) if i not in set(eval_idx)]
    holdout = pick_bucketed(test, holdout_pool, QUOTA['math_final_test'] // 4, 'gsm-final-test')
    holdout_words = [words(test[i]['question']) for i in holdout + eval_idx]
    test_text = eval_text | {norm_text(test[i]['question']) for i in holdout}

    overlap = dict(exact=0, near=0)
    train_pool = []
    for i, r in enumerate(train):
        q = norm_text(r['question'])
        if q in test_text:
            overlap['exact'] += 1
            continue
        w = words(r['question'])
        if any(len(w & h) / max(1, len(w | h)) >= 0.8 for h in holdout_words):
            overlap['near'] += 1
            continue
        train_pool.append(i)
    chosen = pick_bucketed(train, train_pool, QUOTA['math'] // 4, 'gsm-train')

    rows = []
    for n, i in enumerate(chosen, 1):
        r = train[i]
        rid = f'c-math-{n:04d}'
        rows.append(dict(id=rid, category='math', split='train', source=dict(key='gsm8k-train', row=i),
                         en=dict(q=r['question']), wrapper=pick(f'wrap:{rid}', WRAPPER_POOL['math']),
                         thinking=thinking_for(rid), check=dict(type='number', gold=gsm_gold(r['answer'])),
                         reference=dict(solution=r['answer'].split('####')[0].strip()), step_bucket=gsm_bucket(r['answer'])))
    for n, i in enumerate(holdout, 1):
        r = test[i]
        rid = f'c-mathtest-{n:04d}'
        rows.append(dict(id=rid, category='math_final_test', split='final-test', source=dict(key='gsm8k-test', row=i),
                         en=dict(q=r['question']), wrapper=None, thinking=True,
                         check=dict(type='number', gold=gsm_gold(r['answer'])),
                         reference=dict(solution=r['answer'].split('####')[0].strip()), step_bucket=gsm_bucket(r['answer'])))
    manifest['overlap']['gsm8k_train_vs_eval_and_holdout'] = overlap
    return rows


# ---------------------------------------------------------------------------------------------- code

def build_code(manifest):
    train, d1 = load_rows('mbpp-train')
    val, d2 = load_rows('mbpp-validation')
    he, d3 = load_rows('humaneval')
    manifest['sources']['mbpp-train'] = source_info('mbpp-train', d1)
    manifest['sources']['mbpp-validation'] = source_info('mbpp-validation', d2)
    manifest['sources']['humaneval'] = source_info('humaneval', d3)
    he_words = [words(r['prompt']) for r in he]
    he_entry = {r['entry_point'] for r in he}
    pool, flagged = [], []
    for part, rows in (('train', train), ('validation', val)):
        for r in rows:
            w = words(r['text'])
            name = re.search(r'def\s+(\w+)\s*\(', r['code'])
            name = name.group(1) if name else None
            hit = (name in he_entry) or (len(w) >= 6 and any(len(w & h) / len(w) >= 0.8 for h in he_words))
            if hit:
                flagged.append(r['task_id'])
            elif name and not r['text'].strip().endswith('?') and r['test_list']:
                pool.append((part, r))
    manifest['overlap']['mbpp_vs_humaneval_flagged_task_ids'] = sorted(flagged)
    ranked = sorted(pool, key=lambda p: rank(f'mbpp:{p[1]["task_id"]}'))[:QUOTA['code']]
    ranked.sort(key=lambda p: rank(f'order:mbpp:{p[1]["task_id"]}'))
    out = []
    for n, (part, r) in enumerate(ranked, 1):
        rid = f'c-code-{n:04d}'
        out.append(dict(id=rid, category='code', split='train', source=dict(key=f'mbpp-{part}', row=r['task_id']),
                        en=dict(text=r['text'].strip(), tests='\n'.join(r['test_list'])),
                        wrapper=pick(f'wrap:{rid}', WRAPPER_POOL['code']), thinking=thinking_for(rid),
                        check=dict(type='mbpp', setup=r['test_setup_code'] or '', tests=list(r['test_list'])),
                        reference=dict(code=r['code'])))
    return out


# ---------------------------------------------------------------------------------------------- tools

def parse_functions(system):
    decoder = json.JSONDecoder()
    pos, tools = system.find('{'), []
    while 0 <= pos < len(system):
        try:
            obj, end = decoder.raw_decode(system, pos)
        except ValueError:
            return None
        if not isinstance(obj, dict) or 'name' not in obj:
            return None
        tools.append(dict(name=obj['name'], description=obj.get('description', ''),
                          parameters=obj.get('parameters') or dict(type='object', properties={})))
        pos = system.find('{', end)
    return tools


def parse_first_turn(chat):
    user = re.match(r'\s*USER:\s*(.*?)\s*\n\s*\n\s*ASSISTANT:', chat, re.S)
    call = re.match(r'.*?ASSISTANT:\s*<functioncall>\s*(\{.*?\})\s*<\|endoftext\|>', chat, re.S)
    if not user or not call:
        return None
    body = call.group(1)
    name = re.search(r'"name":\s*"([^"]+)"', body)
    args = re.search(r'"arguments":\s*\'(.*)\'\s*\}\s*$', body, re.S)
    if not name or not args or chat.count('<functioncall>') < 1:
        return None
    first_assistant = chat.split('ASSISTANT:', 2)[1]
    if first_assistant.count('<functioncall>') != 1:
        return None
    try:
        parsed = json.loads(args.group(1))
    except ValueError:
        return None
    return user.group(1), name.group(1), parsed


def args_in_user(user, args):
    text = norm_text(user)
    for value in args.values():
        if isinstance(value, bool) or not isinstance(value, (str, int, float)):
            return False
        token = norm_text(str(value))
        if token and token not in text:
            return False
    return True


def types_match(props, args):
    """Argument values must have the JSON type their schema declares (a string-typed zip code must be a string)."""
    for key, value in args.items():
        kind = (props.get(key) or {}).get('type')
        if kind == 'string' and not isinstance(value, str):
            return False
        if kind == 'integer' and not (isinstance(value, int) and not isinstance(value, bool)):
            return False
        if kind == 'number' and not (isinstance(value, (int, float)) and not isinstance(value, bool)):
            return False
    return True


def build_tools(manifest):
    rows, digest = load_rows('glaive')
    manifest['sources']['glaive'] = source_info('glaive', digest)
    bfcl = [json.loads(s) for s in (EVAL_V2 / 'toolcall-pairs.jsonl').read_text(encoding='utf-8').split('\n') if s.strip()]
    bfcl_names = {t['name'] for r in bfcl for t in r['tools']}
    bfcl_text = {norm_text(r['messages'][0]['content']) for r in bfcl}
    pool, dropped = [], dict(parse=0, schema=0, args_not_in_user=0, shape=0, bfcl_overlap=0)
    for index, r in enumerate(rows):
        turn = parse_first_turn(r['chat'])
        tools = parse_functions(r['system'])
        if turn is None or tools is None:
            dropped['parse'] += 1
            continue
        user, name, args = turn
        spec = next((t for t in tools if t['name'] == name), None)
        if spec is None or not isinstance(args, dict) or len(tools) > 3 or len({t['name'] for t in tools}) != len(tools):
            dropped['schema'] += 1
            continue
        params = spec['parameters']
        props = params.get('properties', {}) if isinstance(params, dict) else None
        required = params.get('required', []) if isinstance(params, dict) else None
        if not isinstance(props, dict) or not isinstance(required, list):
            dropped['schema'] += 1
            continue
        if any(k not in props for k in args) or any(k not in args for k in required) or not args:
            dropped['schema'] += 1
            continue
        if not args_in_user(user, args) or not types_match(props, args):
            dropped['args_not_in_user'] += 1
            continue
        if not 20 <= len(user) <= 300 or '\n' in user:
            dropped['shape'] += 1
            continue
        if any(t['name'] in bfcl_names for t in tools) or norm_text(user) in bfcl_text:
            dropped['bfcl_overlap'] += 1
            continue
        pool.append((index, user, tools, name, args))
    manifest['overlap']['glaive_filter_counts'] = dict(dropped, kept_pool=len(pool))
    seen, unique = set(), []
    for item in sorted(pool, key=lambda p: rank(f'glaive:{p[0]}')):
        key = norm_text(item[1])
        if key in seen:
            continue
        seen.add(key)
        unique.append(item)
    chosen = unique[:QUOTA['tool']]
    chosen.sort(key=lambda p: rank(f'order:glaive:{p[0]}'))
    out = []
    for n, (index, user, tools, name, args) in enumerate(chosen, 1):
        rid = f'c-tool-{n:04d}'
        gold = [{name: {k: [v] for k, v in args.items()}}]
        out.append(dict(id=rid, category='tool', split='train', source=dict(key='glaive', row=index), en=dict(user=user),
                        tools=tools, wrapper=None, thinking=thinking_for(rid),
                        check=dict(type='toolcall', gold_calls=gold), reference=dict(call=dict(name=name, arguments=args))))
    return out


# ---------------------------------------------------------------------------------------------- general (English, Turkish)

def build_en_general(manifest):
    """Dolly (human-written English instructions): replay prompts whose answers keep the model's natural length."""
    rows, digest = load_rows('dolly')
    manifest['sources']['dolly'] = source_info('dolly', digest)
    pools, seen = {k: [] for k in DOLLY_QUOTA}, set()
    for index, r in enumerate(rows):
        cat, instruction, context = r['category'], r['instruction'].strip(), (r['context'] or '').strip()
        if cat not in pools or not 15 <= len(instruction) <= 400 or len(context) > 1500 or len(r['response'].strip()) < 30:
            continue
        key = norm_text(instruction)
        if key in seen:
            continue
        seen.add(key)
        pools[cat].append((index, instruction, context, r['response'].strip()))
    picked = []
    for cat, quota in DOLLY_QUOTA.items():
        ranked = sorted(pools[cat], key=lambda p: rank(f'dolly:{p[0]}'))
        if len(ranked) < quota:
            raise ValueError(f'dolly {cat}: only {len(ranked)}')
        picked.extend((cat, p) for p in ranked[:quota])
    picked.sort(key=lambda c: rank(f'order:dolly:{c[1][0]}'))
    out = []
    for n, (cat, (index, instruction, context, response)) in enumerate(picked, 1):
        rid = f'c-engen-{n:04d}'
        user = instruction + (f'\n\n{context}' if context else '')
        out.append(dict(id=rid, category='en_general', split='train', source=dict(key='dolly', row=index, dolly_category=cat),
                        langs=['en'], en=dict(user=user), wrapper=None, thinking=thinking_for(rid),
                        check=dict(type='constraints', items=[]), reference=dict(answer=response)))
    return out


def build_tr_general(manifest):
    """Atlas (native Turkish tasks): grounded tasks with countable constraints, context tasks, plain tasks."""
    sys.path.insert(0, str(ROOT / 'scripts/evaluation'))
    from lfm3_sft_constraints import parse_constraints
    digest = sha256(ATLAS_PATH.read_bytes())
    if digest != ATLAS_INFO['sha256']:
        raise ValueError('Atlas checksum mismatch')
    manifest['sources']['atlas'] = dict(ATLAS_INFO)
    pools, seen, total = dict(constrained=[], context=[], plain=[]), set(), 0
    with ATLAS_PATH.open(encoding='utf-8') as stream:
        for index, line in enumerate(stream):
            total += 1
            msgs = json.loads(line)['messages']
            user, ref = msgs[1]['content'].strip(), msgs[2]['content'].strip()
            if not 120 <= len(user) <= 1200 or not DIACRITICS.search(user) or len(ref) < 20 or ref.startswith('S:'):
                continue
            key = sha256(norm_text(user).encode())
            if key in seen:
                continue
            seen.add(key)
            items = parse_constraints(user)
            group = 'constrained' if items else 'context' if CONTEXT_MARK.search(user) else 'plain'
            pools[group].append((index, user, ref, items))
    if total != ATLAS_INFO['rows']:
        raise ValueError(f'Atlas rows {total}')
    manifest['overlap']['atlas_pools'] = {k: len(v) for k, v in pools.items()}
    picked = []
    for group, quota in TR_GENERAL_QUOTA.items():
        ranked = sorted(pools[group], key=lambda p: rank(f'atlas:{p[0]}'))[:quota]
        picked.extend(ranked)
    picked.sort(key=lambda p: rank(f'order:atlas:{p[0]}'))
    out = []
    for n, (index, user, ref, items) in enumerate(picked, 1):
        rid = f'c-trgen-{n:04d}'
        out.append(dict(id=rid, category='tr_general', split='train', source=dict(key='atlas', row=index), langs=['tr'],
                        tr=dict(user=user), wrapper=None, thinking=thinking_for(rid),
                        check=dict(type='constraints', items=items), reference=dict(answer=ref)))
    return out


