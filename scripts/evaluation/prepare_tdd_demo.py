"""Freeze a task-to-tests demo; CPU/tokenizer only, no model weights."""
import argparse
import gzip
import json
from hashlib import sha256
from pathlib import Path
from active_tdd_data import EXP, ROOT, active_paths, rows, read_json
from native_tdd_labels import encode_conversation, model_fields
from export_intent_only_preview import project_record


def digest(p): return sha256(p.read_bytes()).hexdigest()
def save(p, obj): p.write_text(json.dumps(obj, ensure_ascii=False, indent=2)+'\n', encoding='utf-8', newline='\n')
def lines(p, data): p.write_text(''.join(json.dumps(r, ensure_ascii=False)+'\n' for r in data), encoding='utf-8', newline='\n')


def prepare(tokenizer_path, output):
    from transformers import AutoTokenizer
    out=EXP/output
    if out.exists(): raise ValueError('Preserve existing preflight; choose new revision')
    paths=active_paths(); config=paths['config']
    tokenizer=AutoTokenizer.from_pretrained(tokenizer_path, local_files_only=True, trust_remote_code=False)
    verified=read_json(EXP/'native-label-audit-v01/tokenizer-pin-verification.json')
    for entry in verified['files']:
        if digest(Path(tokenizer_path)/entry['file']) != entry['local_sha256']: raise ValueError('Tokenizer pin changed')
    with gzip.open(EXP/'native-label-audit-v01/encoded-labels.jsonl.gz','rt',encoding='utf-8') as stream:
        audited={r['record_id']:r for r in map(json.loads,stream)}
    train=[r for r in rows(paths['tests']) if r['candidate_split']=='train']
    dev=[r for r in rows(paths['tests']) if r['candidate_split']=='development']
    assert len(train)==50 and len(dev)==5
    assert not {r['source_group'] for r in train} & {r['source_group'] for r in dev}
    train_encoded=[]
    for row in train:
        encoded=model_fields(encode_conversation(tokenizer, project_record(row)['messages'], max_length=3072))
        assert encoded=={k:audited[row['record_id']][k] for k in encoded}
        train_encoded.append(dict(record_id=row['record_id'],**encoded))
    dev_encoded=[dict(record_id=r['record_id'],**model_fields(encode_conversation(tokenizer,project_record(dict(r,candidate_split='train'))['messages'],max_length=3072))) for r in dev]
    requests=[r for r in rows(paths['baseline']/'requests.jsonl') if r['split']=='development']
    assert len(requests)==9 and sum(r['capability']=='task-to-tests' for r in requests)==5
    out.mkdir()
    lines(out/'train-encoded.jsonl',train_encoded);lines(out/'development-encoded.jsonl',dev_encoded)
    lines(out/'development-requests.jsonl',requests)
    # Source-free task references for blinded review only, never generation prompts.
    lines(out/'development-targets.jsonl',[dict(record_id=r['record_id'],target=r['messages'][-1]) for r in dev])
    recipe=dict(model=dict(name=config['model'],revision=config['model_revision']),
        training=dict(method='bf16-lora',epochs=3,learning_rate=1e-4,batch_size=1,gradient_accumulation_steps=8,
                      max_seq_length=3072,seed=3407,optimizer='adamw_8bit',scheduler='cosine',warmup_steps=2,
                      weight_decay=0.0,max_grad_norm=1.0,packing=False,truncation=False,
                      lora=dict(rank=16,alpha=16,dropout=0,target_modules=['q_proj','k_proj','v_proj','o_proj','gate_proj','up_proj','down_proj'])),
        inference=dict(backend='vllm',dtype='bfloat16',temperature=0,max_tokens=2048,seed=3407,
                       max_model_len=8192,enable_thinking=True,repetition_penalty=1.0,stop_token_ids=[248046,248044]),
        evaluation=dict(primary='Blinded paired requirement coverage, correct assertions and anti-cheating review on five development tasks',
                        supporting='Syntax/format, termination, test smells; four other development records are supporting transfer probes',
                        execution='Do not execute generated code on host; protected executor review remains required for runtime claims',
                        split_policy='Repository-held-out transfer; three documented taught-principle overlaps accepted for this demo, not unseen-rule claims',
                        checkpoint='Preselected final epoch; do not tune against holdout',holdout='Not generated by this demo preparation'),
        counts=dict(train=50,development_tests=5,development_requests=len(requests)),
        input_tokens_per_epoch=sum(len(r['input_ids']) for r in train_encoded),
        supervised_tokens_per_epoch=sum(sum(x!=-100 for x in r['labels']) for r in train_encoded),
        inherited_recipe='exp015/016 BF16 LoRA hyperparameters; fresh Qwen base, no response-style adapter; thinking enabled, longer sequences, three epochs',
        training_authorized_only_after_gpu_gates=True)
    save(out/'recipe.json',recipe)
    save(out/'manifest.json',dict(status='local-preflight-passed; GPU gates pending',
        files={p.name:digest(p) for p in out.iterdir() if p.is_file()},
        source_inputs={p.relative_to(ROOT).as_posix():digest(p) for p in [paths['tests'],paths['baseline']/'requests.jsonl',paths['index']]},
        native_label_parity='All 50 sequences exactly match saved audit arrays',
        original_training_preview_sha256=digest(paths['preview']/'tests-train-preview.jsonl')))
    print(json.dumps(recipe,indent=2))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--tokenizer',required=True);p.add_argument('--output',default='demo-preflight-v01')
    a=p.parse_args();prepare(a.tokenizer,a.output)
